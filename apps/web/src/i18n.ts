export type T = (key: string, vars?: Record<string, string | number>) => string
export function translator(locale: Locale): T {
  const language: Record<string, string> = locale === 'it' ? it : en
  return (key, vars = {}) =>
    (language[key] ?? language.unavailable).replace(/\{\{(\w+)\}\}/g, (_, name) =>
      String(vars[name] ?? ''),
    )
}
export function initialLocale(): Locale {
  const value = localStorage.getItem('royale.locale')
  return value === 'it' || (value !== 'en' && navigator.language.toLowerCase().startsWith('it'))
    ? 'it'
    : 'en'
}
export function chipCount(value: number, locale: Locale) {
  return Intl.NumberFormat(locale, { maximumFractionDigits: 1 }).format(value / 10)
}
export function dateTime(at: number, locale: Locale) {
  return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(at)
}
